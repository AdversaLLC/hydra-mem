SLOW = ("vector",)                    # the daemon tests need the RAG virtualenv and take about 40 seconds: only mutants of the daemon and its client run them


def main() -> int:
    args = sys.argv[1:]
    opt = {args[i]: args[i + 1] for i in range(0, len(args) - 1, 2) if args[i] in ("--only", "--tests")}
    only = set(opt["--only"].split(",")) if "--only" in opt else None
    run_only = tuple(opt["--tests"].split(",")) if "--tests" in opt else None     # prove that one suite alone catches a mutant
    chosen = [m for m in MUTANTS if only is None or m[0] in only]
    if only and len(chosen) != len(only):
        print("unknown mutant name(s):", sorted(only - {m[0] for m in MUTANTS}))
        return 2
    survivors = 0
    for name, fname, old, new in chosen:
        d = ROOT / name
        d.mkdir()
        shutil.copytree(REPO / "memsvc", d / "memsvc")
        shutil.copytree(REPO / "tests", d / "tests")
        shutil.copy2(REPO / "memctl", d / "memctl")                          # the CLI tests run it; without it every mutant "dies" for the wrong reason
        f = d / "memsvc" / fname
        s = f.read_text()
        if s.count(old) != 1:
            print(f"{name}: the line to break was not found exactly once ({s.count(old)}); update this script")
            return 2
        f.write_text(s.replace(old, new))
        killed = []
        for t in (run_only or (SLOW if fname in ("vector_daemon.py", "vector.py") else TESTS)):
            p = subprocess.run([sys.executable, "-I", str(d / "tests" / f"test_{t}.py")], capture_output=True, text=True, cwd=d, timeout=600)
            killed += [l.split()[1] for l in (p.stdout + p.stderr).splitlines() if l.startswith(("FAIL:", "ERROR:"))]
        survivors += not killed
        print(f"{name:32s} {'KILLED by ' + ', '.join(killed[:3]) if killed else 'SURVIVED'}")
    print(f"{len(chosen) - survivors} of {len(chosen)} killed; copies are in {ROOT}")
    return 1 if survivors else 0


